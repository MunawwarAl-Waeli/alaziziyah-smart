export function getPostsByCategory(
  categorySlug: string,
  page: number = 1,
  limit: number = 6,
) {
  const filtered = blogPosts.filter(
    (post) => post.category.slug === categorySlug,
  );
  return paginatePosts(filtered, page, limit);
}

export function getPostsByCity(
  citySlug: string,
  page: number = 1,
  limit: number = 6,
) {
  const filtered = blogPosts.filter((post) => post.city?.slug === citySlug);
  return paginatePosts(filtered, page, limit);
}

export function searchPosts(
  query: string,
  page: number = 1,
  limit: number = 6,
) {
  const searchTerm = query.toLowerCase();
  const filtered = blogPosts.filter(
    (post) =>
      post.title.toLowerCase().includes(searchTerm) ||
      post.excerpt.toLowerCase().includes(searchTerm) ||
      post.content.toLowerCase().includes(searchTerm) ||
      post.tags.some((tag) => tag.toLowerCase().includes(searchTerm)),
  );
  return paginatePosts(filtered, page, limit);
}

export function getPostsByTag(
  tag: string,
  page: number = 1,
  limit: number = 6,
) {
  const filtered = blogPosts.filter((post) =>
    post.tags.some((t) => t.toLowerCase() === tag.toLowerCase()),
  );
  return paginatePosts(filtered, page, limit);
}

export function getFeaturedPosts(limit: number = 3) {
  return blogPosts.filter((post) => post.featured).slice(0, limit);
}

export function getRelatedPosts(postId: string, limit: number = 3) {
  const post = blogPosts.find((p) => p.id === postId);
  if (!post) return [];

  return blogPosts
    .filter(
      (p) =>
        p.id !== postId &&
        (p.category.id === post.category.id ||
          p.tags.some((tag) => post.tags.includes(tag))),
    )
    .slice(0, limit);
}

function paginatePosts(
  posts: BlogPost[],
  page: number,
  limit: number,
): PostsResponse {
  const startIndex = (page - 1) * limit;
  const endIndex = startIndex + limit;
  const paginatedPosts = posts.slice(startIndex, endIndex);

  return {
    posts: paginatedPosts,
    pagination: {
      currentPage: page,
      totalPages: Math.ceil(posts.length / limit),
      totalPosts: posts.length,
      postsPerPage: limit,
    },
  };
}
